use crate::model::{McpServer, StoreInputSpec, StoreItem, Transport};
use std::collections::BTreeMap;

fn gh(owner: &str) -> String {
    format!("https://github.com/{owner}.png?size=96")
}

#[allow(clippy::too_many_arguments)]
fn remote(
    id: &str,
    title: &str,
    publisher: &str,
    icon: String,
    homepage: &str,
    url: &str,
    desc: &str,
    sign_in: bool,
    inputs: Vec<StoreInputSpec>,
) -> StoreItem {
    StoreItem {
        id: id.into(),
        name: id.into(),
        title: title.into(),
        description: desc.into(),
        publisher: publisher.into(),
        icon,
        homepage: homepage.into(),
        transport: Transport::Http,
        runs: String::new(),
        sign_in,
        featured: true,
        match_by_addr: false,
        source: "featured".into(),
        stars: None,
        have: None,
        inputs,
        template: McpServer {
            name: id.into(),
            transport: Transport::Http,
            url: url.into(),
            market_id: Some(id.into()),
            ..Default::default()
        },
    }
}

#[allow(clippy::too_many_arguments)]
fn local(
    id: &str,
    title: &str,
    publisher: &str,
    icon: String,
    homepage: &str,
    desc: &str,
    command: &str,
    args: &[&str],
    default_env: &[(&str, &str)],
    inputs: Vec<StoreInputSpec>,
) -> StoreItem {
    let mut env = BTreeMap::new();
    for (k, v) in default_env {
        env.insert((*k).into(), (*v).into());
    }
    StoreItem {
        id: id.into(),
        name: id.into(),
        title: title.into(),
        description: desc.into(),
        publisher: publisher.into(),
        icon,
        homepage: homepage.into(),
        transport: Transport::Stdio,
        runs: command.into(),
        sign_in: false,
        featured: true,
        match_by_addr: false,
        source: "featured".into(),
        stars: None,
        have: None,
        inputs,
        template: McpServer {
            name: id.into(),
            transport: Transport::Stdio,
            command: command.into(),
            args: args.iter().map(|s| (*s).into()).collect(),
            env,
            market_id: Some(id.into()),
            ..Default::default()
        },
    }
}

fn secret_env(key: &str, label: &str, description: &str) -> StoreInputSpec {
    StoreInputSpec {
        key: key.into(),
        where_field: "env".into(),
        label: label.into(),
        description: description.into(),
        placeholder: String::new(),
        secret: true,
        required: true,
        format: String::new(),
    }
}

